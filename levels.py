# -*- coding: utf-8 -*-
"""
levels.py —— 关卡数据

每个关卡是一个字符网格：
  "." 表示空格子
  "^" "v" "<" ">" 分别表示朝上、下、左、右的箭头

第 1 关为手工设计的新手关；第 2~8 关由 v3.0.0 生成器生成并经 solve_order()
可解性求解器校验，保证存在合理的通关顺序。所有关卡都满足方向乱序性：
同一行 / 同一列连续同向箭头不超过 2 个，任意 2×2 区域内不会出现 4 个
同方向箭头扎堆；同时各方向箭头数量均衡（极差 ≤ 1），并且每个方向的
箭头平均位置都贴近棋盘中心（不会出现“左箭头全在左侧、下箭头全在下部”
这类聚在自己指向方向的聚集，四个方向箭头尽量均匀散布在棋盘各处）。

关卡难度逐级增加：箭头密度越来越大（9 -> 16 -> 18 -> 22 -> 42 -> 48 -> 55 -> 62），
后五关失误次数减少为 2 次。

每关还有限时时长（秒）：箭头越多、难度越大，给的限时越长；
通关后按“用时、生命消耗、撤销次数与提示次数”评定 1~5 颗星
（使用 AI 求解直接 1 星，见 game.py 的 Level.stars）。

另提供“挑战关卡”配置：10×10 高密度随机关卡，由 game.py 的
generate_challenge() 在线生成，撤销 / 提示各限 1 次，生命值 3 点。
"""

