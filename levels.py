# -*- coding: utf-8 -*-
"""
levels.py —— 关卡数据

每个关卡是一个字符网格：
  "." 表示空格子
  "^" "v" "<" ">" 分别表示朝上、下、左、右的箭头

第 1 关为手工设计的新手关；第 2~5 关由 tools/generate_level.py
“逆向构造法”随机生成，并全部通过 solve_order() 可解性求解器校验，
保证存在合理的通关顺序。

关卡难度逐级增加：箭头密度越来越大（9 -> 16 -> 18 -> 22 -> 30 个），
后两关失误次数减少为 2 次。随机生成的关卡方向完全打散，
不会出现“一整行全是同一方向”的规律布局。

每关还有限时时长（秒）：箭头越多、难度越大，给的限时越长；
通关后按“用时 + 失误次数”评定 1~3 颗星（见 game.py 的 Level.stars）。
"""

# 关卡 1（5x5）：手工设计的新手入门关，熟悉四方向规则
LEVEL_1 = [
    ". > . ^ .".split(),
    "> . > . ^".split(),
    ". < . v .".split(),
    "< . . . <".split(),
    ". . . . .".split(),
]

# 关卡 2（6x6，16 个箭头）：随机生成，方向交错、分布均匀
LEVEL_2 = [
    ". . < . v .".split(),
    "^ . ^ > . .".split(),
    ". ^ . < > .".split(),
    ". . ^ > . v".split(),
    "^ < . . > .".split(),
    ". . < . > .".split(),
]

# 关卡 3（6x6，18 个箭头）：随机生成，依赖深度加深
LEVEL_3 = [
    "< . ^ . . .".split(),
    "^ . . . . >".split(),
    ". . > ^ > >".split(),
    "< . . > > ^".split(),
    "> . ^ > . .".split(),
    "v > . . . >".split(),
]

# 关卡 4（7x7，22 个箭头）：随机生成，失误次数减少为 2 次
LEVEL_4 = [
    ". < < ^ v < ^".split(),
    ". . ^ . v > .".split(),
    ". < ^ ^ . v <".split(),
    ". ^ > . . . .".split(),
    ". < . . . < .".split(),
    ". v . . . . v".split(),
    "^ > . . . . .".split(),
]

# 关卡 5（8x8，30 个箭头）：随机生成，接近铺满棋盘，本作最高难度
LEVEL_5 = [
    "< < . . < ^ . .".split(),
    ". < v v < . > .".split(),
    "v . . v . . v .".split(),
    ". < . . . > > .".split(),
    ". . < . . > > .".split(),
    "v ^ . v . ^ . ^".split(),
    ". < . . ^ v . .".split(),
    "v v . v . . > .".split(),
]

LEVELS = [LEVEL_1, LEVEL_2, LEVEL_3, LEVEL_4, LEVEL_5]

# 每一关允许的失误次数（越往后越少，增加难度）
MAX_MISTAKES = [3, 3, 3, 2, 2]

# 每一关的限时时长（秒）：箭头越多、难度越大，给的限时越长
TIME_LIMITS = [40, 55, 60, 75, 90]
